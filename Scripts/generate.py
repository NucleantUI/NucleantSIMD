"""Write Sources/NucleantSIMDPortable/Generated/: the simd API, one overload
per type, each a line that calls the generic code in Kernels.swift,
MatrixKernels.swift or QuaternionKernels.swift.

    uv run Scripts/generate.py
"""

from dataclasses import dataclass
from itertools import product
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Sources/NucleantSIMDPortable/Generated"


@dataclass(frozen=True)
class Scalar:
    name: str  # simd name: "float", "uchar"
    swift: str  # Swift type: "Float", "UInt8"
    widths: tuple[int, ...]
    kind: str  # "signed", "unsigned", "float"

    def vector(self, n: int) -> str:
        return self.swift if n == 1 else f"simd_{self.name}{n}"

    @property
    def is_float(self) -> bool:
        return self.kind == "float"


CHAR = Scalar("char", "Int8", (2, 3, 4, 8, 16, 32, 64), "signed")
UCHAR = Scalar("uchar", "UInt8", (2, 3, 4, 8, 16, 32, 64), "unsigned")
SHORT = Scalar("short", "Int16", (2, 3, 4, 8, 16, 32), "signed")
USHORT = Scalar("ushort", "UInt16", (2, 3, 4, 8, 16, 32), "unsigned")
INT = Scalar("int", "Int32", (2, 3, 4, 8, 16), "signed")
UINT = Scalar("uint", "UInt32", (2, 3, 4, 8, 16), "unsigned")
LONG = Scalar("long", "simd_long1", (2, 3, 4, 8), "signed")
ULONG = Scalar("ulong", "simd_ulong1", (2, 3, 4, 8), "unsigned")
FLOAT = Scalar("float", "Float", (2, 3, 4, 8, 16), "float")
DOUBLE = Scalar("double", "Double", (2, 3, 4, 8), "float")

INTEGERS = (CHAR, UCHAR, SHORT, USHORT, INT, UINT, LONG, ULONG)
SIGNED = (CHAR, SHORT, INT, LONG)
FLOATS = (FLOAT, DOUBLE)
ALL = INTEGERS + FLOATS

# The signed integer of the same width: masks for select and bitselect.
MASK = {CHAR: CHAR, UCHAR: CHAR, SHORT: SHORT, USHORT: SHORT, INT: INT, UINT: INT,
        LONG: LONG, ULONG: LONG, FLOAT: INT, DOUBLE: LONG}

HEADER = "// Generated by Scripts/generate.py. Do not edit.\n\n"


def fn(signature: str, body: str) -> str:
    return f"@inlinable public func {signature} {{ {body} }}\n"


def write(name: str, text: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + text)


def float_vectors(widths: tuple[int, ...] | None = None):
    for s in FLOATS:
        for n in s.widths:
            if widths is None or n in widths:
                yield s, n


# MARK: - Types


def types() -> str:
    out = ["public typealias simd_bool = Bool\n\n"]
    for s in ALL:
        swift = {"simd_long1": None, "simd_ulong1": None}.get(s.swift, s.swift)
        if swift is None:
            base = "Int" if s is LONG else "UInt"
            out.append(f"#if _pointerBitWidth(_64)\npublic typealias simd_{s.name}1 = {base}\n"
                       f"#else\npublic typealias simd_{s.name}1 = {base}64\n#endif\n")
        else:
            out.append(f"public typealias simd_{s.name}1 = {swift}\n")
        for n in s.widths:
            out.append(f"public typealias simd_{s.name}{n} = SIMD{n}<{s.swift}>\n")
        out.append("\n")
    for s in ALL:
        widths = [n for n in s.widths if n != 64]
        if s in (LONG, ULONG):
            widths = [1] + widths
        for n in widths:
            out.append(f"public typealias vector_{s.name}{n} = simd_{s.name}{n}\n")
    out.append("\n")
    # Packed: the same vectors (Swift's SIMD types have their scalar's alignment
    # in arrays of scalars already), even widths only.
    for s in ALL:
        for n in s.widths:
            if n == 3:
                continue
            out.append(f"public typealias simd_packed_{s.name}{n} = SIMD{n}<{s.swift}>\n")
    out.append("\n")
    for s in ALL:
        for n in s.widths:
            if n != 3:
                out.append(f"public typealias packed_{s.name}{n} = simd_packed_{s.name}{n}\n")
    out.append("\n")
    for s, el in (("int", "Int32"), ("uint", "UInt32"), ("float", "Float"), ("double", "Double")):
        for n in (2, 3, 4):
            out.append(f'@available(swift, deprecated: 5.1, message: "Use SIMD{n}<{el}>")\n'
                       f"public typealias {s}{n} = SIMD{n}<{el}>\n")
    out.append("\n")
    for s in FLOATS:
        for c, r in product((2, 3, 4), repeat=2):
            out.append(f"public typealias {s.name}{c}x{r} = simd_{s.name}{c}x{r}\n")
            out.append(f"public typealias matrix_{s.name}{c}x{r} = simd_{s.name}{c}x{r}\n")
    out.append("\n")
    out.append(
        "extension SIMD {\n"
        '    @available(swift, deprecated: 5, renamed: "init(repeating:)")\n'
        "    @inlinable public init(_ scalar: Scalar) { self.init(repeating: scalar) }\n"
        "}\n\n"
        "extension SIMD where Scalar: FixedWidthInteger {\n"
        '    @available(swift, deprecated: 5, message: "use 0 &- rhs")\n'
        "    @inlinable public static prefix func - (rhs: Self) -> Self { 0 &- rhs }\n"
        "}\n"
    )
    return "".join(out)


# MARK: - Elementwise math

UNARY_LIBM = ["acos", "acosh", "asin", "asinh", "atan", "atanh", "cbrt", "cos", "cosh", "erf", "erfc",
              "exp", "exp2", "expm1", "lgamma", "log", "log10", "log1p", "log2", "sin", "sinh", "tan",
              "tanh", "tgamma"]
BINARY_LIBM = ["fmod", "hypot", "nextafter", "pow", "remainder"]


def math() -> str:
    out = []
    for s, n in float_vectors():
        v, S = s.vector(n), s.swift
        for f in UNARY_LIBM:
            out.append(fn(f"{f}(_ x: {v}) -> {v}", f"lanewise(x, {S}.libm{f.capitalize()})"))
        out.append(fn(f"atan2(_ y: {v}, _ x: {v}) -> {v}", f"lanewise(y, x, {S}.libmAtan2)"))
        for f in BINARY_LIBM:
            out.append(fn(f"{f}(_ x: {v}, _ y: {v}) -> {v}", f"lanewise(x, y, {S}.libm{f.capitalize()})"))
        out.append(fn(f"exp10(_ x: {v}) -> {v}", "lanewise(x, exp10Scalar)"))
        out.append(fn(f"sinpi(_ x: {v}) -> {v}", "lanewise(x, sinPi)"))
        out.append(fn(f"cospi(_ x: {v}) -> {v}", "lanewise(x, cosPi)"))
        out.append(fn(f"tanpi(_ x: {v}) -> {v}", "lanewise(x, tanPi)"))
        out.append(fn(f"sincos(_ x: {v}) -> (sin: {v}, cos: {v})",
                      f"(lanewise(x, {S}.libmSin), lanewise(x, {S}.libmCos))"))
        out.append(fn(f"sincospi(_ x: {v}) -> (sin: {v}, cos: {v})", "(lanewise(x, sinPi), lanewise(x, cosPi))"))
        out.append(fn(f"fma(_ x: {v}, _ y: {v}, _ z: {v}) -> {v}", "muladdFloat(x, y, z)"))
        out.append(fn(f"round(_ x: {v}) -> {v}", "x.rounded(.toNearestOrAwayFromZero)"))
        m = MASK[s].vector(n)
        out.append(fn(f"isfinite(_ x: {v}) -> {m}", "mask(x) { $0.isFinite }"))
        out.append(fn(f"isinf(_ x: {v}) -> {m}", "mask(x) { $0.isInfinite }"))
        out.append(fn(f"isnan(_ x: {v}) -> {m}", "mask(x) { $0.isNaN }"))
        out.append(fn(f"isnormal(_ x: {v}) -> {m}", "mask(x) { $0.isNormal }"))
        if n <= 4:
            out.append(fn(f"ceil(_ x: {v}) -> {v}", "x.rounded(.up)"))
            out.append(fn(f"floor(_ x: {v}) -> {v}", "x.rounded(.down)"))
            out.append(fn(f"trunc(_ x: {v}) -> {v}", "x.rounded(.towardZero)"))
            out.append(fn(f"fract(_ x: {v}) -> {v}", "fractFloat(x)"))
            out.append(fn(f"fmin(_ x: {v}, _ y: {v}) -> {v}", "minFloat(x, y)"))
            out.append(fn(f"fmax(_ x: {v}, _ y: {v}) -> {v}", "maxFloat(x, y)"))
        out.append("\n")
    return "".join(out)


# MARK: - Common


def common() -> str:
    out = []
    for s in ALL:
        for n in (1,) + s.widths:
            if n == 1 and not s.is_float:
                continue
            v, S = s.vector(n), s.swift
            scalar = n == 1
            kind = "Float" if s.is_float else "Integer"
            if not scalar:
                if s.is_float or s in SIGNED:
                    out.append(fn(f"simd_abs(_ x: {v}) -> {v}", f"abs{kind}(x)"))
                out.append(fn(f"simd_reduce_add(_ x: {v}) -> {S}", "x.sum()" if s.is_float else "x.wrappedSum()"))
                out.append(fn(f"simd_reduce_min(_ x: {v}) -> {S}", "x.min()"))
                out.append(fn(f"simd_reduce_max(_ x: {v}) -> {S}", "x.max()"))
                out.append(fn(f"simd_equal(_ x: {v}, _ y: {v}) -> simd_bool", "x == y"))
            if scalar:
                out.append(fn(f"simd_clamp(_ x: {S}, _ min: {S}, _ max: {S}) -> {S}", "clampFloat(x, min, max)"))
                out.append(fn(f"simd_min(_ x: {S}, _ y: {S}) -> {S}", f"{S}.minimum(x, y)"))
                out.append(fn(f"simd_max(_ x: {S}, _ y: {S}) -> {S}", f"{S}.maximum(x, y)"))
            else:
                out.append(fn(f"simd_clamp(_ x: {v}, _ min: {v}, _ max: {v}) -> {v}", f"clamp{kind}(x, min, max)"))
                out.append(fn(f"simd_min(_ x: {v}, _ y: {v}) -> {v}", f"min{kind}(x, y)"))
                out.append(fn(f"simd_max(_ x: {v}, _ y: {v}) -> {v}", f"max{kind}(x, y)"))
            if s.is_float:
                out.append(fn(f"simd_sign(_ x: {v}) -> {v}", "signFloat(x)"))
                out.append(fn(f"simd_mix(_ x: {v}, _ y: {v}, _ t: {v}) -> {v}", "mixFloat(x, y, t)"))
                recip = "1 / x" if scalar else "recipFloat(x)"
                for f in ("simd_recip", "simd_fast_recip", "simd_precise_recip"):
                    out.append(fn(f"{f}(_ x: {v}) -> {v}", recip))
                for f in ("simd_rsqrt", "simd_fast_rsqrt", "simd_precise_rsqrt"):
                    out.append(fn(f"{f}(_ x: {v}) -> {v}", "rsqrtFloat(x)"))
                out.append(fn(f"simd_fract(_ x: {v}) -> {v}", "fractFloat(x)"))
                out.append(fn(f"simd_step(_ edge: {v}, _ x: {v}) -> {v}", "stepFloat(edge, x)"))
                out.append(fn(f"simd_smoothstep(_ edge0: {v}, _ edge1: {v}, _ x: {v}) -> {v}",
                              "smoothstepFloat(edge0, edge1, x)"))
                out.append(fn(f"simd_muladd(_ x: {v}, _ y: {v}, _ z: {v}) -> {v}",
                              "z.addingProduct(x, y)" if scalar else "muladdFloat(x, y, z)"))
        out.append("\n")

    # The Swift-named functions, for 2, 3 and 4 lanes.
    for s in (FLOAT, DOUBLE, INT, UINT):
        S = s.swift
        kind = "Float" if s.is_float else "Integer"
        for n in (2, 3, 4):
            v = f"SIMD{n}<{S}>"
            if s is not UINT:
                out.append(fn(f"abs(_ x: {v}) -> {v}", f"abs{kind}(x)"))
            out.append(fn(f"clamp(_ x: {v}, min: {v}, max: {v}) -> {v}", f"clamp{kind}(x, min, max)"))
            out.append(fn(f"clamp(_ x: {v}, min: {S}, max: {S}) -> {v}",
                          f"clamp{kind}(x, {v}(repeating: min), {v}(repeating: max))"))
            out.append(fn(f"min(_ x: {v}, _ y: {v}) -> {v}", f"min{kind}(x, y)"))
            out.append(fn(f"max(_ x: {v}, _ y: {v}) -> {v}", f"max{kind}(x, y)"))
            out.append(fn(f"min(_ vector: {v}, _ scalar: {S}) -> {v}", f"min{kind}(vector, {v}(repeating: scalar))"))
            out.append(fn(f"max(_ vector: {v}, _ scalar: {S}) -> {v}", f"max{kind}(vector, {v}(repeating: scalar))"))
            out.append(fn(f"reduce_add(_ x: {v}) -> {S}", "x.sum()" if s.is_float else "x.wrappedSum()"))
            out.append(fn(f"reduce_min(_ x: {v}) -> {S}", "x.min()"))
            out.append(fn(f"reduce_max(_ x: {v}) -> {S}", "x.max()"))
            if s.is_float:
                out.append(fn(f"sign(_ x: {v}) -> {v}", "signFloat(x)"))
                out.append(fn(f"mix(_ x: {v}, _ y: {v}, t: {v}) -> {v}", "mixFloat(x, y, t)"))
                out.append(fn(f"mix(_ x: {v}, _ y: {v}, t: {S}) -> {v}", f"mixFloat(x, y, {v}(repeating: t))"))
                out.append(fn(f"recip(_ x: {v}) -> {v}", "recipFloat(x)"))
                out.append(fn(f"rsqrt(_ x: {v}) -> {v}", "rsqrtFloat(x)"))
                out.append(fn(f"step(_ x: {v}, edge: {v}) -> {v}", "stepFloat(edge, x)"))
                out.append(fn(f"smoothstep(_ x: {v}, edge0: {v}, edge1: {v}) -> {v}", "smoothstepFloat(edge0, edge1, x)"))
        if s.is_float:
            out.append(fn(f"sign(_ x: {S}) -> {S}", "signFloat(x)"))
            out.append(fn(f"recip(_ x: {S}) -> {S}", "1 / x"))
            out.append(fn(f"rsqrt(_ x: {S}) -> {S}", "rsqrtFloat(x)"))
            out.append(fn(f"step(_ x: {S}, edge: {S}) -> {S}", "stepFloat(edge, x)"))
        out.append("\n")
    return "".join(out)


