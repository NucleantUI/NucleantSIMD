# MARK: - Logic


def logic() -> str:
    out = []
    for s in ALL:
        for n in s.widths:
            v, m = s.vector(n), MASK[s].vector(n)
            if not s.is_float:
                out.append(fn(f"simd_any(_ x: {v}) -> simd_bool", "any(topBits(x))"))
                out.append(fn(f"simd_all(_ x: {v}) -> simd_bool", "all(topBits(x))"))
                out.append(fn(f"simd_bitselect(_ x: {v}, _ y: {v}, _ mask: {m}) -> {v}", "bitselectInteger(x, y, mask)"))
            else:
                out.append(fn(f"simd_select(_ x: {v}, _ y: {v}, _ mask: {m}) -> {v}", "select(x, y, mask)"))
                out.append(fn(f"simd_bitselect(_ x: {v}, _ y: {v}, _ mask: {m}) -> {v}", "bitselectFloat(x, y, mask)"))
        out.append("\n")
    return "".join(out)


# MARK: - Conversions


def conversions() -> str:
    out = []
    for target in ALL:
        for n in target.widths:
            if n == 64:
                continue
            r = target.vector(n)
            for source in ALL:
                if n not in source.widths:
                    continue
                v = source.vector(n)
                if target.is_float:
                    body = "convertFloatToFloat(x)" if source.is_float else "convertIntegerToFloat(x)"
                    out.append(fn(f"simd_{target.name}(_ x: {v}) -> {r}", body))
                    continue
                plain = "convertFloatToInteger(x)" if source.is_float else "convertTruncating(x)"
                saturating = "convertFloatToIntegerSaturating(x)" if source.is_float else "convertSaturating(x)"
                out.append(fn(f"simd_{target.name}(_ x: {v}) -> {r}", plain))
                out.append(fn(f"simd_{target.name}_sat(_ x: {v}) -> {r}", saturating))
                if (source is FLOAT and target in (INT, UINT)) or (source is DOUBLE and target in (LONG, ULONG)):
                    out.append(fn(f"simd_{target.name}_rte(_ x: {v}) -> {r}", "convertFloatToIntegerRTE(x)"))
        out.append("\n")
    return "".join(out)


# MARK: - simd_make


def make() -> str:
    out = []
    for s in ALL:
        sources = (1,) + s.widths
        for n in s.widths:
            r = s.vector(n)
            name = f"simd_make_{s.name}{n}"
            # From parts adding up to n lanes.
            if n <= 4:
                for parts in compositions(n):
                    params = ", ".join(f"_ p{i}: {s.vector(k)}" for i, k in enumerate(parts))
                    lanes = ", ".join(lane_list(parts))
                    out.append(fn(f"{name}({params}) -> {r}", f"{r}({lanes})"))
            else:
                h = s.vector(n // 2)
                out.append(fn(f"{name}(_ lo: {h}, _ hi: {h}) -> {r}", f"{r}(lowHalf: lo, highHalf: hi)"))
            # From one vector: its first lanes, zeros after.
            for k in sources:
                body = "resized(x)" if k != n else "x"
                out.append(fn(f"{name}(_ x: {s.vector(k)}) -> {r}", body))
                if k < n:
                    out.append(fn(f"{name}_undef(_ x: {s.vector(k)}) -> {r}", "resized(x)"))
        out.append("\n")
    return "".join(out)


def compositions(n: int):
    """Ordered ways to split n lanes into parts of 1 to 3, not just one part."""
    def go(rest):
        if rest == 0:
            yield ()
            return
        for k in (1, 2, 3):
            if k <= rest:
                for tail in go(rest - k):
                    yield (k,) + tail
    return [c for c in go(n) if len(c) > 1]


def lane_list(parts):
    lanes = []
    for i, k in enumerate(parts):
        if k == 1:
            lanes.append(f"p{i}")
        else:
            lanes.extend(f"p{i}[{j}]" for j in range(k))
    return lanes


# MARK: - Matrices


def matrices() -> str:
    out = []
    for s in FLOATS:
        S = s.swift
        for c, r in product((2, 3, 4), repeat=2):
            out.append(matrix_type(s, c, r))
    for s in FLOATS:
        for n in (2, 3, 4):
            out.append(f"public let matrix_identity_{s.name}{n}x{n} = simd_{s.name}{n}x{n}(1)\n")
    out.append("\n")
    for s in FLOATS:
        out.append(matrix_functions(s))
    return "".join(out)


def mtype(s: Scalar, c: int, r: int) -> str:
    return f"simd_{s.name}{c}x{r}"


def matrix_type(s: Scalar, c: int, r: int) -> str:
    S, T = s.swift, mtype(s, c, r)
    col, row = f"simd_{s.name}{r}", f"simd_{s.name}{c}"
    idx = range(c)
    tup = f"({', '.join([col] * c)})"
    cols = lambda m: [f"{m}.columns.{j}" for j in idx]
    each = lambda expr: "(" + ", ".join(expr(j) for j in idx) + ")"
    d = min(c, r)
    o = []
    o.append(f"/// {c} columns of {r} {S}s.\n")
    o.append(f"@frozen\npublic struct {T}: Sendable {{\n")
    o.append(f"    public var columns: {tup}\n\n")
    o.append(f"    @inlinable public init() {{ columns = {each(lambda j: '.zero')} }}\n\n")
    o.append(f"    @inlinable public init(columns: {tup}) {{ self.columns = columns }}\n")
    o.append("}\n\n")
    o.append(f"extension {T} {{\n")
    o.append(f"    /// `scalar` along the diagonal, zero elsewhere.\n")
    o.append(f"    @inlinable public init(_ scalar: {S}) {{ self.init(diagonal: simd_{s.name}{d}(repeating: scalar)) }}\n\n")
    o.append(f"    @inlinable public init(diagonal: SIMD{d}<{S}>) {{\n        self.init()\n")
    for j in range(d):
        o.append(f"        columns.{j}[{j}] = diagonal[{j}]\n")
    o.append("    }\n\n")
    o.append(f"    @inlinable public init(_ columns: [SIMD{r}<{S}>]) {{\n"
             f"        precondition(columns.count == {c}, \"Requires array of {c} vectors\")\n"
             f"        self.init(columns: {each(lambda j: f'columns[{j}]')})\n    }}\n\n")
    o.append(f"    @inlinable public init(rows: [SIMD{c}<{S}>]) {{\n"
             f"        precondition(rows.count == {r}, \"Requires array of {r} vectors\")\n"
             f"        self.init(columns: {each(lambda j: col + '(' + ', '.join(f'rows[{i}][{j}]' for i in range(r)) + ')')})\n    }}\n\n")
    params = ", ".join(f"_ col{j}: SIMD{r}<{S}>" for j in idx)
    o.append(f"    @inlinable public init({params}) {{ self.init(columns: ({', '.join(f'col{j}' for j in idx)})) }}\n\n")
    o.append(f"    @inlinable public init(_ cmatrix: {T}) {{ self = cmatrix }}\n\n")
    o.append(f"    @inlinable public var cmatrix: {T} {{ self }}\n\n")
    o.append(f"    @inlinable public subscript(column: Int) -> SIMD{r}<{S}> {{\n        get {{\n"
             f"            switch column {{\n")
    for j in idx:
        o.append(f"            case {j}: return columns.{j}\n")
    o.append(f"            default: preconditionFailure(\"Column index out of range\")\n            }}\n        }}\n"
             f"        set {{\n            switch column {{\n")
    for j in idx:
        o.append(f"            case {j}: columns.{j} = newValue\n")
    o.append(f"            default: preconditionFailure(\"Column index out of range\")\n            }}\n        }}\n    }}\n\n")
    o.append(f"    @inlinable public subscript(column: Int, row: Int) -> {S} {{\n"
             f"        get {{ self[column][row] }}\n        set {{ self[column][row] = newValue }}\n    }}\n\n")
    o.append(f"    @inlinable public var transpose: {mtype(s, r, c)} {{\n"
             f"        {mtype(s, r, c)}(columns: (" +
             ", ".join(row + "(" + ", ".join(f"columns.{j}[{i}]" for j in idx) + ")" for i in range(r)) + "))\n    }\n")
    if c == r:
        args = ", ".join(f"columns.{j}" for j in idx)
        o.append(f"\n    @inlinable public var inverse: {T} {{ {T}(columns: NucleantSIMDPortable.inverse({args})) }}\n\n")
        o.append(f"    @inlinable public var determinant: {S} {{ NucleantSIMDPortable.determinant({args}) }}\n")
        if c in (3, 4):
            q = "simd_quatf" if s is FLOAT else "simd_quatd"
            o.append(f"\n    /// The rotation `quaternion` makes.\n"
                     f"    @inlinable public init(_ quaternion: {q}) {{\n"
                     f"        let r = rotationColumns(quaternion.vector)\n")
            if c == 3:
                o.append("        self.init(columns: r)\n    }\n")
            else:
                o.append(f"        self.init(columns: (simd_{s.name}4(r.0, 0), simd_{s.name}4(r.1, 0), simd_{s.name}4(r.2, 0), simd_{s.name}4(0, 0, 0, 1)))\n    }}\n")
    o.append("}\n\n")
    o.append(f"extension {T}: CustomDebugStringConvertible {{\n"
             f"    @inlinable public var debugDescription: String {{\n"
             f"        \"{T}([" + ", ".join(f"\\(arrayDescription(columns.{j}))" for j in idx) + "])\"\n    }\n}\n\n")
    o.append(f"extension {T}: Equatable {{\n"
             f"    @inlinable public static func == (lhs: {T}, rhs: {T}) -> Bool {{\n"
             f"        " + " && ".join(f"lhs.columns.{j} == rhs.columns.{j}" for j in idx) + "\n    }\n}\n\n")
    o.append(f"extension {T} {{\n")
    o.append(f"    @inlinable public static func + (lhs: {T}, rhs: {T}) -> {T} {{ {T}(columns: {each(lambda j: f'lhs.columns.{j} + rhs.columns.{j}')}) }}\n")
    o.append(f"    @inlinable public static prefix func - (rhs: {T}) -> {T} {{ {T}(columns: {each(lambda j: f'-rhs.columns.{j}')}) }}\n")
    o.append(f"    @inlinable public static func - (lhs: {T}, rhs: {T}) -> {T} {{ {T}(columns: {each(lambda j: f'lhs.columns.{j} - rhs.columns.{j}')}) }}\n")
    o.append(f"    @inlinable public static func += (lhs: inout {T}, rhs: {T}) {{ lhs = lhs + rhs }}\n")
    o.append(f"    @inlinable public static func -= (lhs: inout {T}, rhs: {T}) {{ lhs = lhs - rhs }}\n")
    o.append(f"    @inlinable public static func * (lhs: {S}, rhs: {T}) -> {T} {{ {T}(columns: {each(lambda j: f'lhs * rhs.columns.{j}')}) }}\n")
    o.append(f"    @inlinable public static func * (lhs: {T}, rhs: {S}) -> {T} {{ rhs * lhs }}\n")
    o.append(f"    @inlinable public static func *= (lhs: inout {T}, rhs: {S}) {{ lhs = lhs * rhs }}\n")
    combo = " + ".join(f"lhs.columns.{j} * rhs[{j}]" for j in idx)
    o.append(f"    @inlinable public static func * (lhs: {T}, rhs: SIMD{c}<{S}>) -> SIMD{r}<{S}> {{ {combo} }}\n")
    o.append(f"    @inlinable public static func * (lhs: SIMD{r}<{S}>, rhs: {T}) -> SIMD{c}<{S}> {{\n"
             f"        SIMD{c}(" + ", ".join(f"dotFloat(lhs, rhs.columns.{j})" for j in idx) + ")\n    }\n")
    for k in (2, 3, 4):
        R, P = mtype(s, k, c), mtype(s, k, r)
        o.append(f"    @inlinable public static func * (lhs: {T}, rhs: {R}) -> {P} {{\n"
                 f"        {P}(columns: (" + ", ".join(f"lhs * rhs.columns.{j}" for j in range(k)) + "))\n    }\n")
    o.append(f"    @inlinable public static func *= (lhs: inout {T}, rhs: {mtype(s, c, c)}) {{ lhs = lhs * rhs }}\n")
    o.append("}\n\n")
    return "".join(o)


def matrix_functions(s: Scalar) -> str:
    S = s.swift
    o = []
    for c, r in product((2, 3, 4), repeat=2):
        T = mtype(s, c, r)
        col, row = s.vector(r), s.vector(c)
        cparams = ", ".join(f"_ col{j}: {col}" for j in range(c))
        cargs = ", ".join(f"col{j}" for j in range(c))
        rparams = ", ".join(f"_ row{i}: {row}" for i in range(r))
        rargs = ", ".join(f"row{i}" for i in range(r))
        o.append(fn(f"simd_matrix({cparams}) -> {T}", f"{T}(columns: ({cargs}))"))
        o.append(fn(f"simd_matrix_from_rows({rparams}) -> {T}", f"{T}(rows: [{rargs}])"))
        o.append(fn(f"simd_mul(_ a: {S}, _ x: {T}) -> {T}", "a * x"))
        o.append(fn(f"matrix_scale(_ a: {S}, _ x: {T}) -> {T}", "a * x"))
        o.append(fn(f"simd_linear_combination(_ a: {S}, _ x: {T}, _ b: {S}, _ y: {T}) -> {T}", "a * x + b * y"))
        o.append(fn(f"simd_add(_ x: {T}, _ y: {T}) -> {T}", "x + y"))
        o.append(fn(f"simd_sub(_ x: {T}, _ y: {T}) -> {T}", "x - y"))
        o.append(fn(f"simd_transpose(_ x: {T}) -> {mtype(s, r, c)}", "x.transpose"))
        o.append(fn(f"simd_equal(_ x: {T}, _ y: {T}) -> simd_bool", "x == y"))
        elementwise = " && ".join(
            f"all(absFloat(x.columns.{j} - y.columns.{j}) .<= {{tol}})" for j in range(c))
        o.append(fn(f"simd_almost_equal_elements(_ x: {T}, _ y: {T}, _ tol: {S}) -> simd_bool",
                    elementwise.replace("{tol}", f"{col}(repeating: tol)")))
        o.append(fn(f"simd_almost_equal_elements_relative(_ x: {T}, _ y: {T}, _ tol: {S}) -> simd_bool",
                    " && ".join(f"all(absFloat(x.columns.{j} - y.columns.{j}) .<= tol * absFloat(x.columns.{j}))" for j in range(c))))
        for k in (2, 3, 4):
            R, P = mtype(s, k, c), mtype(s, k, r)
            o.append(fn(f"simd_mul(_ x: {T}, _ y: {R}) -> {P}", "x * y"))
            o.append(fn(f"matrix_multiply(_ x: {T}, _ y: {R}) -> {P}", "x * y"))
        o.append(fn(f"simd_mul(_ x: {T}, _ y: {row}) -> {col}", "x * y"))
        o.append(fn(f"simd_mul(_ x: {col}, _ y: {T}) -> {row}", "x * y"))
        o.append(fn(f"matrix_multiply(_ x: {T}, _ y: {row}) -> {col}", "x * y"))
        o.append(fn(f"matrix_multiply(_ x: {col}, _ y: {T}) -> {row}", "x * y"))
        o.append(fn(f"matrix_from_columns({cparams}) -> {T}", f"{T}(columns: ({cargs}))"))
        o.append(fn(f"matrix_from_rows({rparams}) -> {T}", f"{T}(rows: [{rargs}])"))
        o.append(fn(f"matrix_transpose(_ x: {T}) -> {mtype(s, r, c)}", "x.transpose"))
        o.append(fn(f"matrix_equal(_ x: {T}, _ y: {T}) -> Bool", "x == y"))
        if c == r:
            v = s.vector(c)
            o.append(fn(f"simd_diagonal_matrix(_ x: {v}) -> {T}", f"{T}(diagonal: x)"))
            o.append(fn(f"matrix_from_diagonal(_ x: {v}) -> {T}", f"{T}(diagonal: x)"))
            o.append(fn(f"simd_inverse(_ x: {T}) -> {T}", "x.inverse"))
            o.append(fn(f"matrix_invert(_ x: {T}) -> {T}", "x.inverse"))
            o.append(fn(f"simd_determinant(_ x: {T}) -> {S}", "x.determinant"))
            o.append(fn(f"matrix_determinant(_ x: {T}) -> {S}", "x.determinant"))
            o.append(fn(f"simd_trace(_ x: {T}) -> {S}", " + ".join(f"x.columns.{j}[{j}]" for j in range(c))))
        o.append("\n")
    return "".join(o)


